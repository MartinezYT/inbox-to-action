"""FastAPI app: the HTTP layer that ties triage, storage, and notifications together.

Run locally:  uvicorn app.main:app --reload
Docs:         http://localhost:8000/docs  (auto-generated by FastAPI)
"""

from __future__ import annotations

import hmac
import json
import logging
import threading
import time
from collections import defaultdict, deque
from pathlib import Path

from fastapi import BackgroundTasks, Depends, FastAPI, Header, HTTPException, Query, Request
from fastapi.responses import HTMLResponse

from .config import Settings, get_settings
from .dashboard import DASHBOARD_HTML
from .models import Category, IncomingMessage, ProcessedMessage, Stats, Triage
from .notify import send_alerts
from .store import Store
from .triage import TriageService

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s: %(message)s")
log = logging.getLogger("inbox")

SAMPLES = Path(__file__).resolve().parent.parent / "evals" / "dataset.jsonl"


def seed_demo(store: Store, service: TriageService) -> None:
    """Triage the sample messages so a fresh demo dashboard isn't empty."""
    if store.stats().total or not SAMPLES.exists():
        return
    for line in SAMPLES.read_text().splitlines():
        if not line.strip():
            continue
        msg = IncomingMessage.model_validate(json.loads(line)["input"])
        triage, engine = service.triage(msg)
        store.add(msg, triage, engine)
    log.info("Seeded demo data")


class RateLimiter:
    """In-memory sliding window. Good enough for one small demo instance."""

    def __init__(self, per_minute: int):
        self.per_minute = per_minute
        self.hits: dict[str, deque[float]] = defaultdict(deque)

    def allow(self, key: str) -> bool:
        now = time.monotonic()
        q = self.hits[key]
        while q and now - q[0] > 60:
            q.popleft()
        if len(q) >= self.per_minute:
            return False
        q.append(now)
        return True


def create_app(settings: Settings | None = None, claude_client=None) -> FastAPI:
    settings = settings or get_settings()
    store = Store(settings.database_path)
    service = TriageService(settings, claude_client=claude_client)
    limiter = RateLimiter(settings.demo_rate_per_minute)

    app = FastAPI(
        title="Inbox-to-Action",
        description="AI agent that triages inbound business messages and turns them into actions.",
        version="1.0.0",
    )
    app.state.settings, app.state.store, app.state.service = settings, store, service

    if settings.demo_mode and settings.seed_demo_data:
        # Background thread: startup stays fast even when each sample goes to Claude.
        threading.Thread(target=seed_demo, args=(store, service), daemon=True).start()

    # ------------------------------------------------------------------ auth helpers
    def require_key(x_api_key: str | None = Header(default=None)) -> None:
        if not settings.api_key:
            return  # auth disabled (local dev)
        if not x_api_key or not hmac.compare_digest(x_api_key, settings.api_key):
            raise HTTPException(status_code=401, detail="Invalid or missing X-API-Key")

    def require_key_unless_demo(x_api_key: str | None = Header(default=None)) -> None:
        if settings.demo_mode:
            return
        require_key(x_api_key)

    def check_length(msg: IncomingMessage) -> None:
        if len(msg.body) > settings.max_message_chars:
            raise HTTPException(status_code=413, detail="Message body too long")

    # ------------------------------------------------------------------ routes
    @app.get("/health")
    def health() -> dict:
        return {"status": "ok", "engine": "claude" if service.claude else "rules",
                "model": settings.claude_model if service.claude else None,
                "demo_mode": settings.demo_mode}

    @app.post("/api/messages", response_model=ProcessedMessage, status_code=201,
              dependencies=[Depends(require_key)])
    def ingest(msg: IncomingMessage, background: BackgroundTasks) -> ProcessedMessage:
        """Main webhook: triage a message, save it, alert the team in the background."""
        check_length(msg)
        triage, engine = service.triage(msg)
        processed = store.add(msg, triage, engine)
        log.info("message %s -> %s/%s via %s", processed.id, triage.category.value,
                 triage.urgency.value, engine)
        background.add_task(_notify, processed)
        return processed

    def _notify(processed: ProcessedMessage) -> None:
        if send_alerts(settings, processed):
            store.mark_notified(processed.id)

    @app.post("/api/try", response_model=Triage)
    def try_it(msg: IncomingMessage, request: Request) -> Triage:
        """Public, rate-limited playground for the portfolio demo. Results are NOT stored."""
        if not settings.demo_mode:
            raise HTTPException(status_code=404, detail="Not found")
        ip = request.headers.get("x-forwarded-for", request.client.host if request.client else "?")
        if not limiter.allow(ip.split(",")[0].strip()):
            raise HTTPException(status_code=429, detail="Slow down - try again in a minute")
        check_length(msg)
        triage, _ = service.triage(msg)
        return triage

    @app.get("/api/messages", response_model=list[ProcessedMessage],
             dependencies=[Depends(require_key_unless_demo)])
    def list_messages(category: Category | None = None,
                      limit: int = Query(50, ge=1, le=200)) -> list[ProcessedMessage]:
        return store.list(category.value if category else None, limit)

    @app.get("/api/messages/{message_id}", response_model=ProcessedMessage,
             dependencies=[Depends(require_key_unless_demo)])
    def get_message(message_id: int) -> ProcessedMessage:
        found = store.get(message_id)
        if not found:
            raise HTTPException(status_code=404, detail="Message not found")
        return found

    @app.get("/api/stats", response_model=Stats, dependencies=[Depends(require_key_unless_demo)])
    def stats() -> Stats:
        return store.stats()

    @app.get("/", response_class=HTMLResponse, include_in_schema=False)
    def dashboard() -> str:
        if not settings.demo_mode:
            return ("<h1>Inbox-to-Action</h1><p>API is running. See <a href='/docs'>/docs</a>. "
                    "Set DEMO_MODE=true to enable the public dashboard.</p>")
        return DASHBOARD_HTML.replace("{{BUSINESS}}", settings.business_name)

    return app


app = create_app()
